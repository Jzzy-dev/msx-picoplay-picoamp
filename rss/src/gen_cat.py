#!/usr/bin/env python3
# feeds_cat.c (the PicoAmp engine's catalogue) -> cat.inc for the reader
import re, sys
src = open(sys.argv[1]).read()
topics = re.findall(r'\{\s*"([^"]+)"\s*\}', src.split('pva_news_topics')[1].split('};')[0])
feeds = re.findall(r'\{\s*(\d+),\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)"\s*\}', src)
defs = re.search(r'pva_news_default_favs\[\]\s*=\s*"([^"]*)"', src).group(1)
o = ['; generated by gen_cat.py from feeds_cat.c - do not edit',
     'CAT_NTOPICS equ %d' % len(topics), 'cat_topics:']
for t in topics: o.append('        db "%s",0' % t)
o.append('cat_feeds:                      ; topic, code, name, URL')
for t, c, n, u in feeds:
    assert '"' not in n + u
    o.append('        db %s,"%s",0,"%s",0,"%s",0' % (t, c, n, u))
o.append('        db #FF')
o.append('cat_default: db "%s",0' % defs)
open(sys.argv[2], 'w').write('\n'.join(o) + '\n')
print(len(topics), 'topics', len(feeds), 'feeds', sum(len(c)+len(n)+len(u)+4 for _, c, n, u in feeds), 'bytes')
