#!/bin/sh
# PICOAMP.COM (MSX-DOS) and PICOAMP.ROM (the PicoAmp ROM mode, loadrom -pa),
# and the LoadROM tool's copy of the ROM (tool/src/picoamp_rom.h)
set -e
cd "$(dirname "$0")"
python3 gen_tables.py > tables.inc
sjasmplus --nologo --msg=war --raw=PICOAMP.COM picoamp.asm
sjasmplus --nologo --msg=war -DROMBUILD --raw=PICOAMP.ROM picoamp.asm
# the LoadROM tool's copy, when this folder is in a PicoVerse tree (see assemble.sh)
[ -d ../loadrom.pio/tool/src ] && python3 - <<'PY'
d = open('PICOAMP.ROM', 'rb').read()
o = ['// generated by msxdos-player/build.sh from PICOAMP.ROM', 'unsigned char picoamp_rom[] = {']
for i in range(0, len(d), 12):
    o.append('  ' + ', '.join('0x%02x' % b for b in d[i:i + 12]) + (',' if i + 12 < len(d) else ''))
o += ['};', 'unsigned int picoamp_rom_len = %d;' % len(d)]
open('../loadrom.pio/tool/src/picoamp_rom.h', 'w').write('\n'.join(o) + '\n')
PY
ls -l PICOAMP.COM PICOAMP.ROM
