#!/usr/bin/env python3
# tables.inc for PICOAMP.COM: python3 gen_tables.py > tables.inc
#
# The picture area (oscilloscope, equalizer) is 24 x 10 cells = 192 x 80
# pixels, kept in RAM as 10 rows of 24 cells x 8 bytes (the order of the
# VDP's pattern table), so a pixel (x, y) is the byte
#   (y >> 3) * 192 + (x & F8h) + (y & 7),  bit 7 - (x & 7)
W, H = 192, 80
GREEN, YELLOW, RED, NAVY, BLUE_D = 8, 9, 11, 14, 2

print('; generated by gen_tables.py')
# scope: signed sample byte (the engine's sample / 256) -> y, 0 = top
ys = []
for b in range(256):
    v = b - 256 if b >= 128 else b
    y = 40 - (v * 5) // 8
    ys.append(max(0, min(H - 1, y)))
print('scope_y:')
for i in range(0, 256, 16):
    print('        db ' + ','.join('%d' % v for v in ys[i:i + 16]))
# y -> byte offset of its line in the first cell column
print('row_off:')
for i in range(0, H, 8):
    print('        dw ' + ','.join('%d' % ((y >> 3) * W + (y & 7)) for y in range(i, i + 8)))
# scope colours by line: green in the middle, yellow, red at the edges, a dim
# centre line
cols = []
for y in range(H):
    d = abs(y - 39.5)
    fg = GREEN if d < 22 else YELLOW if d < 33 else RED
    bg = BLUE_D if y == 40 else NAVY
    cols.append(fg * 16 + bg)
print('scope_col:')
for i in range(0, H, 16):
    print('        db ' + ','.join('#%02X' % v for v in cols[i:i + 16]))

# full screen: big bars, 20 cells (40 segments): level 0..31 -> lit segments
print('fs_segof:')
print('        db ' + ','.join('%d' % round(l * 40 / 31) for l in range(32)))
GREEN_, YELLOW_, ORANGE_, RED_, CYAN_, BLUE_, WHITE_ = 8, 9, 10, 11, 4, 3, 5
segs = []
for sgm in range(40):
    fg = GREEN_ if sgm < 22 else YELLOW_ if sgm < 30 else ORANGE_ if sgm < 35 else RED_
    segs.append(fg * 16 + NAVY)
print('fs_segcol:')
for i in range(0, 40, 10):
    print('        db ' + ','.join('#%02X' % v for v in segs[i:i + 10]))
# mirror: cyan to white
segs = []
for sgm in range(20):
    fg = BLUE_ if sgm < 6 else CYAN_ if sgm < 16 else WHITE_
    segs.append(fg * 16 + NAVY)
print('mir_segcol:')
print('        db ' + ','.join('#%02X' % v for v in segs))
# plasma: a sine 0..63
import math
print('sin64:')
sv = [int(round(31.5 + 31.5 * math.sin(i * 2 * math.pi / 256))) for i in range(256)]
for i in range(0, 256, 16):
    print('        db ' + ','.join('%d' % v for v in sv[i:i + 16]))
# ordered dither: f of 8 pixels set, two line phases
order = [0, 4, 2, 6, 1, 5, 3, 7]
def dpat(f, ph):
    b = 0
    for k in range(f):
        b |= 0x80 >> ((order[k] + ph * 1) % 8)
    return b
print('dither:')
print('        db ' + ','.join('#%02X' % dpat(f, 0) for f in range(8)))
print('        db ' + ','.join('#%02X' % dpat(f, 4) for f in range(8)))
# a colour wheel of 48 steps (RGB 0..7): the plasma's palette turns round it
wheel = []
for i in range(48):
    h = i / 48.0
    r = max(0, min(1, abs(h * 6 - 3) - 1)); g = max(0, min(1, 2 - abs(h * 6 - 2))); b = max(0, min(1, 2 - abs(h * 6 - 4)))
    wheel += [int(round(r * 7)), int(round(g * 7)), int(round(b * 7))]
print('wheel:')
for i in range(0, 48 * 3, 24):
    print('        db ' + ','.join('%d' % v for v in wheel[i:i + 24]))
# brightness 0..7: v * b / 7
print('bright:')
for b in range(8):
    print('        db ' + ','.join('%d' % (v * b // 7) for v in range(8)))
