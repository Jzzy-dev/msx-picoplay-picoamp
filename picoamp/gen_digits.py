#!/usr/bin/env python3
# digits.inc: 7-segment digits for PICOAMP.COM, 2 x 3 cells (16 x 24 pixels) each,
# cells in the order top-left, top-right, middle-left, ..., then the colon (1 x 3).
import sys
sys.path.insert(0, 'mockups')
from mockup import digit_rows, colon_rows

def cells(rows, w):
    out = []
    for ty in range(3):
        for tx in range(w):
            for r in range(8):
                bits = rows[ty * 8 + r][tx * 8: tx * 8 + 8]
                out.append(int(''.join('1' if c == '#' else '0' for c in bits), 2))
    return out

print('; generated by gen_digits.py')
print('digits:')
for d in '0123456789':
    b = cells(digit_rows(d), 2)
    for i in range(0, len(b), 8):
        print('        db ' + ','.join('#%02X' % v for v in b[i:i + 8]))
print('colon:')
b = cells(colon_rows(), 1)
for i in range(0, len(b), 8):
    print('        db ' + ','.join('#%02X' % v for v in b[i:i + 8]))
